#!/usr/bin/env python3
"""Why do citations fail? Audit every rejected citation in the saved runs.

The investigator accepts a citation only if its quote is (nearly) verbatim in
the exact sentence it names. This script looks at each rejected one and asks
where the quote actually lives, if anywhere:

  neighbour      verbatim in a sentence one or two ids away, same document
  spans          starts in the cited sentence and runs on into the next one
  same_document  verbatim elsewhere in the cited document
  other_document verbatim in a different document
  not_in_archive nowhere in the surviving archive: paraphrased or invented

Only the first four are misfiled pointers to real evidence; the last is a
ghost in the strict sense. The game still rejects all of them.

    python benchmarks/citation_audit.py      # writes benchmarks/citation_audit.md
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "server"))

from lastwitness import archive  # noqa: E402
from lastwitness.investigator import _norm, quote_matches  # noqa: E402

RUNS = ROOT / "benchmarks" / "runs"
OUT = ROOT / "benchmarks" / "citation_audit.md"
KINDS = ("neighbour", "spans", "same_document", "other_document", "not_in_archive")


def _split(sid: str) -> tuple[str, str, int]:
    doc, s = sid.split(":")
    return doc, s[0], int(s[1:])


def classify(sid: str, quote: str, index: dict[str, str]) -> str:
    doc, kind, n = _split(sid)
    for d in (1, -1, 2, -2):
        other = f"{doc}:{kind}{n + d}"
        if other in index and quote_matches(quote, index[other]):
            return "neighbour"
    q = _norm(quote)
    run_on = _norm(" ".join(index[f"{doc}:{kind}{n + d}"] for d in range(4) if f"{doc}:{kind}{n + d}" in index))
    sent = _norm(index.get(sid, ""))
    if q and sent and q in run_on and (sent in q or q[:20] in sent):
        return "spans"
    same = [t for k, t in index.items() if k.startswith(doc + ":")]
    if any(quote_matches(quote, t) for t in same) or q in _norm(" ".join(same)):
        return "same_document"
    if any(quote_matches(quote, t) for t in index.values()):
        return "other_document"
    return "not_in_archive"


def citations(log: dict):
    """Yield (where, claim_or_answer, citation) for every citation in a spike or benchmark run."""
    for f in log.get("free", []):
        for c in f["claims"]:
            for x in c["citations"]:
                yield "ask", c, x
    for f in log.get("form", []):
        for x in f["citations"]:
            yield "form", f, x
    for call in log.get("calls", []):
        for x in call.get("citations", []):
            yield "form", call, x


def audit() -> str:
    index = archive.sentence_index()
    rows, examples = [], []
    total = Counter()
    for f in sorted(RUNS.glob("*.json")):
        log = json.loads(f.read_text(encoding="utf-8"))
        label = log["model"] + (" (thinking)" if log.get("config", {}).get("think") is True else "")
        c = Counter()
        for where, owner, x in citations(log):
            c["cited"] += 1
            if x["valid"]:
                c["valid"] += 1
                continue
            k = classify(x["sentence_id"], x["quote"], index)
            c[k] += 1
            if sum(e[0] == k for e in examples) < 3:
                examples.append((k, f.name, x["sentence_id"], x["quote"], index.get(x["sentence_id"], "")))
        total.update(c)
        rows.append((label, f.name, c))
    lines = ["# Citation audit", "",
             "Generated by `benchmarks/citation_audit.py` from the raw runs in `benchmarks/runs/`.",
             "A citation is valid only when its quote is (nearly) verbatim in the exact sentence it names. "
             "For every rejected citation this table shows where the quoted text actually is.", "",
             "| model | run | citations | valid | neighbour sentence | runs into next sentence | same document | "
             "other document | not in archive |",
             "|---|---|---|---|---|---|---|---|---|"]
    for label, name, c in rows + [("all runs", "", total)]:
        if not c["cited"]:
            continue
        pct = f" ({100 * c['valid'] // c['cited']}%)"
        lines.append(f"| {label} | {name} | {c['cited']} | {c['valid']}{pct} | " +
                     " | ".join(str(c[k]) for k in KINDS) + " |")
    bad = sum(total[k] for k in KINDS)
    if bad:
        misfiled = bad - total["not_in_archive"]
        lines += ["", f"Of {bad} rejected citations, {misfiled} ({100 * misfiled // bad}%) quote text that exists in "
                  f"the archive under a different sentence id; {total['not_in_archive']} quote text that is not in "
                  "the archive at all.", ""]
    if examples:
        lines += ["## Examples", ""]
        for k, name, sid, quote, actual in examples:
            lines += [f"- **{k}** ({name}): cited `{sid}` with \"{quote[:160]}\"", f"  - `{sid}` actually says: \"{actual[:160]}\""]
        lines.append("")
    text = "\n".join(lines)
    OUT.write_text(text, encoding="utf-8")
    return text


if __name__ == "__main__":
    print(audit())
